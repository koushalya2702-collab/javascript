// Operators in JavaScript


let a = 10;
let b = 3;

console.log(a + b); // 13
console.log(a - b); // 7
console.log(a * b); // 30
console.log(a / b); // 3.33
console.log(a % b); // 1

// Assignment Operators

let x = 10;

x += 5; // x = x + 5
x -= 2; // x = x - 2

console.log(x);

